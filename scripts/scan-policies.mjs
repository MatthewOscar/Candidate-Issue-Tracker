// Weekly scan of every pool repo's contribution docs for AI-policy language.
// Output (data/ai-policy-scan.json) is the STAFF review queue rendered on the
// site's /review page — it is never shown to students as a verdict. Staff
// promote confirmed findings into data/ai-policies.json.
//
// Rate math: ~656 repos x 9 paths, batched 20 repos/query -> ~33 GraphQL
// requests weekly. Every scanned repo appears in the output (empty hits =
// "scanned clean"), so clean is distinguishable from never-scanned.
import { appendFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { GitHub } from './lib/github.mjs';
import { commitAndPush } from './lib/git-commit.mjs';

export const DOC_PATHS = [
  'CONTRIBUTING.md',
  '.github/CONTRIBUTING.md',
  'docs/CONTRIBUTING.md',
  'README.md',
  '.github/PULL_REQUEST_TEMPLATE.md',
  'GOVERNANCE.md',
  'CODE_OF_CONDUCT.md',
  'AGENTS.md',
  '.github/copilot-instructions.md',
];

// Word-boundary phrases that suggest an AI-contribution stance. Tuned for
// recall over precision (staff review the hits); bare "AI" is excluded — the
// pool is full of ML projects and it would drown the queue.
export const KEYWORDS = [
  'ai-generated',
  'ai generated',
  'ai-assisted',
  'ai assisted',
  'ai-created',
  'ai contribution',
  'ai contributions',
  'ai policy',
  'ai tool',
  'ai tools',
  'ai usage',
  'use of ai',
  'generative ai',
  'llm',
  'llms',
  'large language model',
  'chatgpt',
  'gpt-4',
  'copilot',
  'claude',
  'machine-generated',
  'machine generated',
  'autogenerated code',
  'slop',
];

const MAX_TEXT = 100_000;
const SNIPPET_RADIUS = 160;
const BATCH_SIZE = 20;
const BATCH_PAUSE_MS = 500;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const keywordRes = KEYWORDS.map((k) => ({
  keyword: k,
  re: new RegExp(`(?<![\\w-])${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\w-])`, 'gi'),
}));

export function scanText(text) {
  const hits = [];
  const clipped = text.slice(0, MAX_TEXT);
  for (const { keyword, re } of keywordRes) {
    re.lastIndex = 0;
    const m = re.exec(clipped);
    if (!m) continue;
    const start = Math.max(0, m.index - SNIPPET_RADIUS);
    const end = Math.min(clipped.length, m.index + keyword.length + SNIPPET_RADIUS);
    hits.push({
      keyword,
      snippet: `${start > 0 ? '…' : ''}${clipped.slice(start, end).replace(/\s+/g, ' ').trim()}${
        end < clipped.length ? '…' : ''
      }`,
    });
  }
  return hits;
}

export function buildRepoBatchQuery(repoKeys) {
  const parts = repoKeys.map(([owner, name], i) => {
    const objects = DOC_PATHS.map(
      (p, j) => `p${j}: object(expression: ${JSON.stringify(`HEAD:${p}`)}) { ... on Blob { text } }`,
    ).join('\n      ');
    return `repo${i}: repository(owner: ${JSON.stringify(owner)}, name: ${JSON.stringify(name)}) {
      nameWithOwner isArchived
      ${objects}
    }`;
  });
  return `query {\n${parts.join('\n')}\n}`;
}

export function scanRepoNode(node, repoKey, now) {
  if (!node) return { scannedAt: now, error: 'repo-missing', hits: [] };
  const entry = { scannedAt: now, error: node.isArchived ? 'archived' : null, hits: [] };
  DOC_PATHS.forEach((docPath, j) => {
    const text = node[`p${j}`]?.text;
    if (!text) return;
    for (const hit of scanText(text)) {
      entry.hits.push({
        path: docPath,
        keyword: hit.keyword,
        snippet: hit.snippet,
        url: `https://github.com/${repoKey}/blob/HEAD/${docPath}`,
      });
    }
  });
  return entry;
}

/** Equality that ignores generatedAt/scannedAt so unchanged weeks don't commit. */
export function scansEqual(a, b) {
  const strip = (doc) =>
    JSON.stringify(
      Object.fromEntries(
        Object.entries(doc.repos ?? {}).map(([k, v]) => [k, { error: v.error, hits: v.hits }]),
      ),
    );
  return strip(a) === strip(b);
}

async function main() {
  const dryRun = Boolean(process.env.DRY_RUN);
  const limit = Number(process.env.LIMIT) || Infinity;
  const token = process.env.GITHUB_TOKEN;
  if (!token) throw new Error('GITHUB_TOKEN is required');
  const [owner, repo] = (process.env.GITHUB_REPOSITORY ?? 'MatthewOscar/Candidate-Issue-Tracker').split('/');
  const api = new GitHub({ token, owner, repo });

  const issuesDoc = JSON.parse(await readFile('data/issues.json', 'utf8'));
  const previous = JSON.parse(await readFile('data/ai-policy-scan.json', 'utf8'));
  const repoKeys = [...new Set(issuesDoc.issues.map((i) => i.repoKey ?? `${i.org.toLowerCase()}/${i.repo.toLowerCase()}`))]
    .sort()
    .slice(0, limit);

  const now = new Date().toISOString();
  const repos = {};
  let withHits = 0;
  for (let start = 0; start < repoKeys.length; start += BATCH_SIZE) {
    const batch = repoKeys.slice(start, start + BATCH_SIZE);
    const data = await api.graphql(
      buildRepoBatchQuery(batch.map((k) => k.split('/'))),
      {},
    );
    batch.forEach((key, i) => {
      const entry = scanRepoNode(data?.[`repo${i}`], key, now);
      if (entry.hits.length) withHits++;
      repos[key] = entry;
    });
    console.log(`scanned ${Math.min(start + BATCH_SIZE, repoKeys.length)}/${repoKeys.length}`);
    if (start + BATCH_SIZE < repoKeys.length) await sleep(BATCH_PAUSE_MS);
  }

  const next = { generatedAt: now, repos };
  const newHitRepos = Object.entries(repos)
    .filter(([k, v]) => v.hits.length && !(previous.repos?.[k]?.hits?.length))
    .map(([k]) => k);
  console.log(`repos with hits: ${withHits}; newly hit since last scan: ${newHitRepos.length}`);
  for (const k of newHitRepos) console.log(`  new: ${k}`);

  let pushed = false;
  if (limit !== Infinity) {
    console.log('LIMIT set — probe run, not writing ai-policy-scan.json');
  } else if (scansEqual(previous, next)) {
    console.log('no changes — skipping commit');
  } else {
    if (!dryRun) await writeFile('data/ai-policy-scan.json', JSON.stringify(next, null, 1) + '\n');
    pushed = commitAndPush({
      files: ['data/ai-policy-scan.json'],
      message: `policy-scan: weekly sweep (${withHits} repos with hits, ${newHitRepos.length} new)`,
      dryRun,
    });
  }
  if (process.env.GITHUB_OUTPUT) {
    await appendFile(process.env.GITHUB_OUTPUT, `changed=${pushed}\n`);
  }
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);
if (isMain) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
